// Circle-based icons also need a <circle>; declare them here.
const CIRCLES = { clock: [12, 12, 9], alert: [12, 12, 9], help: [12, 12, 9], search: [11, 11, 7], bug: [12, 13, 5], globe: [12, 12, 9] };
const RECTS = { clipboard: [6, 4, 12, 17, 2] };

function buildSvg(name) {
  const parts = [];
  const r = RECTS[name];
  if (r) parts.push(`<rect x='${r[0]}' y='${r[1]}' width='${r[2]}' height='${r[3]}' rx='${r[4]}'/>`);
  const c = CIRCLES[name];
  if (c) parts.push(`<circle cx='${c[0]}' cy='${c[1]}' r='${c[2]}'/>`);
  if (ICONS[name]) parts.push(`<path d='${ICONS[name]}'/>`);
  const body = parts.join("");
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${body}</svg>`;
}

function toUrl(svg) {
  const enc = svg
    .replace(/#/g, "%23")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E")
    .replace(/"/g, "'")
    .replace(/\s+/g, " ");
  return `url("data:image/svg+xml,${enc}")`;
}

const iconRules = Object.keys(ICONS)
  .map((name) => `.ds-ic[data-ic="${name}"] { --ds-icon: ${toUrl(buildSvg(name))}; }`)
